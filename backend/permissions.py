ALIASES = {"milestone.update": "construction.update", "milestone.undo": "construction.undo"}


def hcode(code: str) -> str:
    return code


def expand(codes) -> list[str]:
    """Legacy coarse code → set of specific codes (identity for specific codes). Used for role/grant migration and old `can()` calls."""
    out: set[str] = set()
    for c in codes:
        c = ALIASES.get(c, c)
        out.update(LEGACY_EXPANSION.get(c, [c]))
    return sorted(out)


def canonical(code: str) -> str:
    return ALIASES.get(code, code)


