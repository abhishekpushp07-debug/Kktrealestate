def _label(action: str) -> str:
    return action.replace("_", " ").capitalize()


def registry_rows() -> list[dict]:
    rows = []
    route_codes = {c for v in ROUTE_PERMS.values() for c in v["codes"]}
    for mod, (mlabel, feats) in REGISTRY.items():
        for feat, (flabel, actions) in feats.items():
            for a in actions:
                code = f"{mod}.{feat}.{a}"
                rows.append({"code": code, "hcode": code, "module": mod, "module_label": mlabel, "feature": feat, "feature_label": flabel, "action": a,
                             "label": f"{_label(a)} {flabel.lower()}", "ui_only": code not in route_codes and code in UI_ONLY, "reserved": code not in route_codes and code not in UI_ONLY})
    return rows


